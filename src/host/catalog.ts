import { resolveInRoot, writeFileAtomic } from './files.js'
import { readTextFile } from './files.js'
import { checksumOf, type Entry } from './model.js'
import { serializeEntry } from './frontmatter.js'
import { DERIVED_FILES } from './paths.js'

export const GENERATED_HEADER = '<!-- GENERATED by dsh-general-automatic-memory · do not edit · rebuild: /memory doctor -->'

export interface IndexLimits {
  /** INDEX.md 硬上限，对齐 Claude Code auto memory 的实测值 */
  maxLines: number
  maxBytes: number
}

export const INDEX_LIMITS: IndexLimits = { maxLines: 200, maxBytes: 25_600 }

/** INDEX.md 的分组顺序 = 裁剪优先级，越前越不该被裁 */
const GROUP_ORDER = ['feedback', 'persona', 'preference', 'relations', 'project', 'reference', 'procedure'] as const

interface Group {
  kind: string
  label: string
  rows: string[]
  omitted: number
}

/**
 * 由 frontmatter 反向生成 INDEX.md。**永不手写**——这是治「索引与内容漂移」
 * 这个文件式记忆头号故障的唯一办法。
 *
 * 排序必须确定性（heat desc, id asc），否则注入文本会随文件系统返回顺序抖动，
 * 直接击穿 DeepSeek 前缀缓存（原则 P4）。
 */
export function renderIndex(entries: Entry[], limits: IndexLimits = INDEX_LIMITS): string {
  const active = entries.filter((e) => e.meta.temporal.invalidatedAt === null)
  const byKind = new Map<string, Entry[]>()
  for (const entry of active) {
    const list = byKind.get(entry.meta.kind) ?? []
    list.push(entry)
    byKind.set(entry.meta.kind, list)
  }

  const groups: Group[] = []
  for (const kind of GROUP_ORDER) {
    const list = (byKind.get(kind) ?? []).slice().sort(byRank)
    if (list.length === 0) continue
    groups.push({
      kind,
      label: GROUP_LABEL[kind] ?? kind,
      rows: list.map((e) => `- [${e.meta.title}](${e.rel}) — ${e.meta.summary}`),
      omitted: 0,
    })
    byKind.delete(kind)
  }
  // 未在 GROUP_ORDER 里的 kind（例如未来扩展）也要出现，不能静默丢
  for (const [kind, list] of [...byKind.entries()].sort((a, b) => (a[0] < b[0] ? -1 : 1))) {
    const sorted = list.slice().sort(byRank)
    groups.push({ kind, label: kind, rows: sorted.map((e) => `- [${e.meta.title}](${e.rel}) — ${e.meta.summary}`), omitted: 0 })
  }

  const header = (omittedTotal: number, bytes: number) =>
    [
      GENERATED_HEADER,
      `<!-- entries: ${active.length} · omitted: ${omittedTotal} · bytes: ${bytes} / ${limits.maxBytes} · lines: ${limits.maxLines} -->`,
      '',
    ].join('\n')

  // 先按全量渲染，超预算再从最后一个分组开始整行裁剪（被裁数量写进头部，可观测不静默）
  let omittedTotal = 0
  for (let attempt = 0; attempt < 60; attempt++) {
    const body = groups
      .map((g) => {
        const shown = g.rows.slice(0, g.rows.length - g.omitted)
        const tail = g.omitted > 0 ? [`- … +${g.omitted} more via memory_recall`] : []
        return [`## ${g.label} (${shown.length + g.omitted})`, ...shown, ...tail].join('\n')
      })
      .join('\n\n')
    const text = `${header(omittedTotal, Buffer.byteLength(body, 'utf8'))}\n${body}\n`
    const lines = text.split('\n').length
    const bytes = Buffer.byteLength(text, 'utf8')
    if (lines <= limits.maxLines && bytes <= limits.maxBytes) return text

    // 从优先级最低的分组开始裁
    for (let i = groups.length - 1; i >= 0; i--) {
      const g = groups[i] as Group
      if (g.omitted < g.rows.length) {
        g.omitted++
        omittedTotal++
        break
      }
    }
  }
  return header(omittedTotal, 0) + '\n(index over budget even after trimming; run /memory doctor)\n'
}

const GROUP_LABEL: Record<string, string> = {
  feedback: '反馈 feedback',
  persona: '画像 persona',
  preference: '偏好 preference',
  relations: '关系 relations',
  project: '项目 project',
  reference: '参考 reference',
  procedure: '程序 procedure',
}

function byRank(a: Entry, b: Entry): number {
  const heat = b.meta.stats.heat - a.meta.stats.heat
  if (heat !== 0) return heat
  return a.meta.id < b.meta.id ? -1 : a.meta.id > b.meta.id ? 1 : 0
}

/**
 * PROFILE.md：给**其他 agent 工具**直接读的画像汇编。
 * 只收 activation=always 的 persona/preference/feedback，按 kind 分段。
 */
export function renderProfile(entries: Entry[], maxChars: number): string {
  const pick = (kind: string) =>
    entries
      .filter((e) => e.meta.kind === kind && e.meta.activation === 'always' && e.meta.temporal.invalidatedAt === null)
      .sort(byRank)

  const sections: Array<[string, Entry[]]> = [
    ['关于用户', pick('persona')],
    ['协作纪律', pick('feedback')],
    ['偏好', pick('preference')],
  ]

  const lines: string[] = [GENERATED_HEADER, '']
  let used = lines.join('\n').length
  for (const [title, list] of sections) {
    if (list.length === 0) continue
    const block = [`## ${title}`]
    for (const entry of list) {
      const line = `- ${entry.meta.title}：${entry.body.trim().split('\n')[0] ?? entry.meta.summary}`
      if (used + line.length + 1 > maxChars) {
        block.push(`- …（其余 ${list.length - (block.length - 1)} 条见 INDEX.md）`)
        break
      }
      block.push(line)
      used += line.length + 1
    }
    lines.push('', ...block)
    used += title.length + 5
  }
  return `${lines.join('\n').trim()}\n`
}

/** 关系边表：派生物，供族谱视图与 memory_graph 使用。 */
export function renderGraphJsonl(entries: Entry[]): string {
  const edges: string[] = []
  for (const entry of entries.filter((e) => e.meta.kind === 'relations').sort(byRank)) {
    const [from, to] = entry.meta.entities
    if (!from || !to) continue
    edges.push(
      JSON.stringify({
        from,
        rel: relationOf(entry),
        to,
        mid: entry.meta.id,
        conf: entry.meta.confidence,
        validFrom: entry.meta.temporal.validFrom,
        invalidatedAt: entry.meta.temporal.invalidatedAt,
      }),
    )
  }
  return edges.length > 0 ? `${edges.join('\n')}\n` : ''
}

const RELATION_WORDS = ['负责', '汇报给', '属于', '依赖', '使用', '位于', '参与', '取代', '冲突于']

function relationOf(entry: Entry): string {
  const haystack = `${entry.meta.title}\n${entry.body}`
  return RELATION_WORDS.find((w) => haystack.includes(w)) ?? '关联'
}

/**
 * 把所有派生文件一次性写回。写前先比对 checksum，内容没变就不落盘——
 * 避免每次固化都改动 mtime，进而让 watcher 与同步误判为「有变更」。
 */
export async function writeDerived(
  root: string,
  files: Array<[string, string]>,
  write: (abs: string, data: string) => Promise<void>,
  read: (abs: string) => Promise<string | null>,
): Promise<{ written: string[]; unchanged: string[] }> {
  const written: string[] = []
  const unchanged: string[] = []
  for (const [rel, content] of files) {
    const abs = resolveInRoot(root, rel)
    const existing = await read(abs)
    if (existing !== null && checksumOf(existing) === checksumOf(content)) {
      unchanged.push(rel)
      continue
    }
    await writeFileAtomic(abs, content)
    written.push(rel)
  }
  return { written, unchanged }
}

export function derivedFiles(entries: Entry[], budget: { alwaysChars: number }): Array<[string, string]> {
  return [
    [DERIVED_FILES[0], renderIndex(entries)],
    [DERIVED_FILES[1], renderProfile(entries, budget.alwaysChars)],
    [DERIVED_FILES[3], renderGraphJsonl(entries)],
  ]
}

export async function readDerived(root: string, rel: string): Promise<string | null> {
  return readTextFile(path.join(root, rel))
}
